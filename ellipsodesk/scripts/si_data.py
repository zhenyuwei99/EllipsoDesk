SALZBERG_COEFF = (10.6684293, 0.301516485, 0.0030434748, 1.13475115, 1.54133408, 1104.0)

def _salzberg_n(w_nm):
    w_um = np.asarray(w_nm, float) / 1000.0
    b1, c1, b2, c2, b3, c3 = SALZBERG_COEFF
    n2 = 1.0 + b1 * w_um**2 / (w_um**2 - c1) + b2 * w_um**2 / (w_um**2 - c2) + b3 * w_um**2 / (w_um**2 - c3)
    return np.sqrt(n2)

def si_nk(eV):
    eV = np.atleast_1d(np.asarray(eV, float))
    w_nm = 1239.841984 / eV
    n = np.empty_like(w_nm)
    k = np.zeros_like(w_nm)
    m_asp = w_nm <= 826.6
    m_gr = (~m_asp) & (w_nm <= 1450.0)
    m_sz = (~m_asp) & (~m_gr)
    n[m_asp] = np.interp(w_nm[m_asp], ASPNES_WNM, ASPNES_N)
    k[m_asp] = np.interp(w_nm[m_asp], ASPNES_WNM, ASPNES_K)
    n[m_gr] = np.interp(w_nm[m_gr], GREEN_WNM, GREEN_N)
    k[m_gr] = np.interp(w_nm[m_gr], GREEN_WNM, GREEN_K)
    n[m_sz] = _salzberg_n(w_nm[m_sz])
    return n - 1j * k

